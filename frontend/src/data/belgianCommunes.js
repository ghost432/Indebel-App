const getProvinceForCommune = (commune) => {
  const prefix = String(commune.code || '').slice(0, 2)
  return PROVINCES_BY_NIS_PREFIX[prefix] || ''
}

const withProvince = (commune) => ({
  ...commune,
  province: getProvinceForCommune(commune)
})

export const getCommunesForRegion = (region) => (BELGIAN_COMMUNES_BY_REGION[region] || []).map(withProvince)

export const getProvincesForRegion = (region) => {
  if (PROVINCES_BY_REGION[region]) return PROVINCES_BY_REGION[region]
  return []
}

export const getCommunesForRegionAndProvince = (region, province) => {
  const communes = getCommunesForRegion(region)
  if (!province) return communes
  return communes.filter((commune) => commune.province === province)
}
