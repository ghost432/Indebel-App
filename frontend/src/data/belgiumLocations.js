// Fonction helper pour générer la liste plate de toutes les villes
export const getAllCities = () => {
  const cities = [];
  
  Object.entries(belgiumRegions).forEach(([region, data]) => {
    if (region === 'Région de Bruxelles-Capitale') {
      cities.push(...data.communes.map(city => ({ city, region })));
    } else {
      Object.entries(data).forEach(([province, communes]) => {
        cities.push(...communes.map(city => ({ city, region, province })));
      });
    }
  });
  
  return cities.sort((a, b) => a.city.localeCompare(b.city, 'fr'));
};
